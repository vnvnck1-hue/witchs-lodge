const {chromium}=require('C:/Users/Loadcomplete/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('path');
const fs=require('fs');
const {pathToFileURL}=require('url');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page=await browser.newPage({viewport:{width:1440,height:1080},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'report.html')).href);
  await page.locator('.hero').evaluate(img=>img.decode());
  const articleCount=await page.locator('article').count();
  await page.screenshot({path:path.join(__dirname,'report-preview.png')});
  await page.getByRole('button',{name:'우선 P1',exact:true}).click();
  const p1visible=await page.locator('article:visible').count();
  await page.getByRole('button',{name:'개발용',exact:true}).click();
  const devVisible=await page.locator('article:visible').count();
  await page.getByRole('button',{name:'모든 상세 항목',exact:true}).click();
  await page.locator('article .detail').first().click();
  await page.locator('#full').evaluate(img=>img.decode());
  const dialogOpen=await page.locator('dialog[open]').count()===1;
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(__dirname,'report-mobile-preview.png')});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  const images=await page.locator('img').evaluateAll(xs=>xs.filter(x=>!x.loading||x.loading!=='lazy').map(x=>({src:x.getAttribute('src'),valid:x.complete&&x.naturalWidth>0})));
  const result={articleCount,p1visible,devVisible,dialogOpen,mobileOverflow:overflow,errors,images};
  fs.writeFileSync(path.join(__dirname,'report-verification.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  await browser.close();
  if(articleCount!==30||devVisible!==1||!dialogOpen||overflow||errors.length)process.exit(1);
})();
